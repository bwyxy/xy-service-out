/**
 * 公共正则（偏向「常用且可预期」的校验）
 *
 */
export const REGEX = {
  /** 中国大陆手机号码 */
  cnMobile: /^1\d{10}$/,

  /** Email */
  email: /^[^\s@]+@[^\s@]+\.[^\s@]+$/,

  /** 身份证 */
  cnId18: /^\d{17}[\dXx]$/,

  /** IPv4 */
  ipv4: /^(?:(?:25[0-5]|2[0-4]\d|1?\d?\d)\.){3}(?:25[0-5]|2[0-4]\d|1?\d?\d)$/,

  /** URL（必須有 http/https） */
  httpUrl: /^https?:\/\/[^\s/$.?#].[^\s]*$/i,

  /** 6 位數验证码 */
  otp6: /^\d{6}$/,

  /** 中文 */
  chinese: /^[\u4e00-\u9fa5]+$/,

  /** 发票抬头 */
  lookUp: /^[\u4E00-\u9FA5]{2,10}(·[\u4E00-\u9FA5]{2,10}){0,2}$/,

  /** 发票税号 */
  dutyParagraph: /^[A-Z0-9]{15}$|^[A-Z0-9]{17}$|^[A-Z0-9]{18}$|^[A-Z0-9]{20}$/
} as const;

